#pragma once

/** @brief Provides the definitions for various primitives as shorter-named ones. */

typedef char      s8;
typedef short     s16;
typedef int       s32;
typedef long long s64;

/* Unsigned variations. We should prefer these instead over the available macros. */
typedef unsigned char      u8;
typedef unsigned short     u16;
typedef unsigned int       u32;
typedef unsigned long long u64;
